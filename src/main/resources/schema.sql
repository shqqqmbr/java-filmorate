DROP TABLE IF EXISTS review_likes;
DROP TABLE IF EXISTS reviews;
DROP TABLE IF EXISTS feed;
DROP TABLE IF EXISTS likes;
DROP TABLE IF EXISTS friends;
DROP TABLE IF EXISTS film_genres;
DROP TABLE IF EXISTS film_directors;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS films;
DROP TABLE IF EXISTS directors;
DROP TABLE IF EXISTS genres;
DROP TABLE IF EXISTS mpa;

CREATE TABLE IF NOT EXISTS mpa
(
    mpa_id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mpa_name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS genres
(
    genre_id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS directors
(
    director_id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS users
(
    id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR,
    login VARCHAR NOT NULL,
    email VARCHAR NOT NULL,
    birthday DATE
);

CREATE TABLE IF NOT EXISTS films
(
    id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    description VARCHAR NOT NULL,
    duration INT NOT NULL,
    release_date DATE NOT NULL,
    mpa INT NOT NULL REFERENCES mpa(mpa_id) ON DELETE RESTRICT ON UPDATE CASCADE
    );

CREATE TABLE IF NOT EXISTS film_genres
(
    film_id INT NOT NULL REFERENCES films(id) ON DELETE CASCADE ON UPDATE CASCADE,
    genre_id INT NOT NULL REFERENCES genres(genre_id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (film_id, genre_id)
    );

CREATE TABLE IF NOT EXISTS film_directors
(
    film_id INT NOT NULL REFERENCES films(id) ON DELETE CASCADE ON UPDATE CASCADE,
    director_id INT NOT NULL REFERENCES directors(director_id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (film_id, director_id)
    );

CREATE TABLE IF NOT EXISTS friends
(
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    friend_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    status BOOLEAN NOT NULL,
    PRIMARY KEY (user_id, friend_id)
    );

CREATE TABLE IF NOT EXISTS likes
(
    film_id INT NOT NULL REFERENCES films(id) ON DELETE CASCADE ON UPDATE CASCADE,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (film_id, user_id)
    );

CREATE TABLE IF NOT EXISTS feed
(
    event_id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id INT NOT NULL,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    timestamp TIMESTAMP(9) NOT NULL,
    event_type VARCHAR NOT NULL,
    operation_type VARCHAR NOT NULL
    );

CREATE TABLE IF NOT EXISTS reviews
(
    review_id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    is_positive BOOLEAN NOT NULL,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    film_id INT NOT NULL REFERENCES films(id) ON DELETE CASCADE ON UPDATE CASCADE
    );

CREATE TABLE IF NOT EXISTS review_likes
(
    review_id INT NOT NULL REFERENCES reviews(review_id) ON DELETE CASCADE ON UPDATE CASCADE,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    useful INT NOT NULL CHECK (useful IN (-1, 1)),
    PRIMARY KEY (review_id, user_id)
    );